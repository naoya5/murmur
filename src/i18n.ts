export const strings: Record<Locale, Strings> = { en, ja };

/** The OS language, reduced to the two the UI has. */
export function systemLocale(): Locale {
  const lang = typeof navigator === "undefined" ? "en" : navigator.language;
  return lang.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export function resolveLocale(ui: UiLanguage): Locale {
  return ui === "system" ? systemLocale() : ui;
}

/** Name of a spoken language in the UI language. */
export function languageName(t: Strings, language: Language): string {
  return language === "ja" ? t.common.japanese : t.common.english;
}

export const I18nContext = createContext<Strings>(en);

export function useT(): Strings {
  return useContext(I18nContext);
}
